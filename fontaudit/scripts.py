_STARTS = [a for a, _, _ in SCRIPT_RANGES]


def script_of(cp: int) -> str:
    i = bisect_right(_STARTS, cp) - 1
    if i >= 0:
        a, b, s = SCRIPT_RANGES[i]
        if a <= cp <= b:
            return s
    cat = unicodedata.category(chr(cp))
    if cat in ("Mn", "Mc", "Me"):
        return "Zinh"
    if cat == "Zzzz" or cat == "Cn":
        return "Zzzz"
    return "Zyyy"
